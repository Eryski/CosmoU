const { contextBridge, ipcRenderer: r } = require('electron');
contextBridge.exposeInMainWorld('api', {
  getSettings: () => r.invoke('settings'),
  scan: () => r.invoke('scan'),
  pickCemu: () => r.invoke('pickCemu'),
  pickFolder: () => r.invoke('pickFolder'),
  play: p => r.invoke('play', p),
  openCovers: () => r.invoke('covers'),
  showInFolder: p => r.invoke('showInFolder', p),
  getMusic: () => r.invoke('music'),
  openMusicFolder: () => r.invoke('musicFolder'),
  setOnlineCovers: v => r.invoke('setOnlineCovers', v),
  setGameSetting: (k, v) => r.invoke('setGameSetting', k, v),
  cemuSettingsGet: () => r.invoke('cemuSettingsGet'),
  setCemuSetting: (k, v) => r.invoke('setCemuSetting', k, v),
  setDefaultQuality: n => r.invoke('setDefaultQuality', n),
  onCoversUpdated: cb => r.on('covers-updated', () => cb()),
  inputGet: s => r.invoke('inputGet', s),
  inputSet: (s, k, v) => r.invoke('inputSet', s, k, v),
  inputProfile: (s, a, n) => r.invoke('inputProfile', s, a, n),
  inputOpenCemu: () => r.invoke('inputOpenCemu'),
  gpList: (t, n) => r.invoke('gpList', t, n),
  gpSet: (t, n, id, on, p) => r.invoke('gpSet', t, n, id, on, p),
  gpDownload: () => r.invoke('gpDownload'),
  onGpProgress: cb => r.on('gp-progress', (_, d) => cb(d)),
  feedbackInfo: () => r.invoke('feedbackInfo'),
  openIssue: b => r.invoke('openIssue', b),
  openDiscord: () => r.invoke('openDiscord'),
  autoOptimize: (t, n, k, gpu) => r.invoke('autoOptimize', t, n, k, gpu),
  appPick: () => r.invoke('appPick'),
  appCoverPick: () => r.invoke('appCoverPick'),
  appSave: a => r.invoke('appSave', a),
  appRemove: id => r.invoke('appRemove', id),
  appGet: id => r.invoke('appGet', id),
  mergePlays: p => r.invoke('mergePlays', p),
  setTheme: t => r.invoke('setTheme', t),
  checkUpdate: () => r.invoke('checkUpdate'),
  openReleases: () => r.invoke('openReleases'),
  setSetupDone: v => r.invoke('setSetupDone', v),
  pickMusic: () => r.invoke('pickMusic'),
  resetMusic: () => r.invoke('resetMusic'),
  themeMusic: id => r.invoke('themeMusic', id),
  exportSettings: ui => r.invoke('exportSettings', ui),
  importSettings: () => r.invoke('importSettings'),
  cemuStatus: () => r.invoke('cemuStatus'),
  cemuInstall: () => r.invoke('cemuInstall'),
  cemuCancel: () => r.invoke('cemuCancel'),
  onCemuProgress: cb => r.on('cemu-progress', (_, d) => cb(d)),
});
